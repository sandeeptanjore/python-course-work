#capitalize()
s1='hello dear students'
print(s1.capitalize()) #Hello dear students

#upper()
print(s1.upper()) #HELLO DEAR STUDENTS

#lower() - works only for English language
print(s1.lower()) #hello dear students

#title()
print(s1.title()) #Hello Dear Students

#swapcase()
print(s1.swapcase()) #HELLO DEAR STUDENTS

#casefold() - same as lower() but can be used for any non English and English language
print(s1.casefold()) #hello dear students

